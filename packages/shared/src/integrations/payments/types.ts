/**
 * Payment gateway contract (Component 6).
 *
 * This is the only place WorkPay talks to an external payment provider. The
 * interface models three outcomes explicitly:
 *
 *   - Success   : the operation definitively succeeded.
 *   - Declined  : the provider definitively refused. A classified failure.
 *   - Unknown   : the outcome cannot be determined (timeout, network error,
 *                 ambiguous response). The caller MUST reconcile rather than
 *                 retry blindly or assume failure.
 *
 * Modelling UNKNOWN as a first-class result is what prevents double captures
 * and silent losses when the network is unreliable.
 */
import type { Money } from "../../platform/money.js";

export interface AuthorizeRequest {
  /** Merchant order id, generated by WorkPay and sent to the provider. */
  orderId: string;
  amount: Money;
  description: string;
  /** Idempotency key so a retried authorize does not create a new authorization. */
  idempotencyKey: string;
}

export interface AuthorizeResult {
  status: "SUCCESS" | "DECLINED" | "UNKNOWN";
  /** Provider authorization id, present on success. */
  authorizationId?: string;
  /** Provider order id, present on success. */
  providerOrderId?: string;
  /** Machine-readable failure code when declined. */
  errorCode?: string;
  errorMessage?: string;
}

export interface CaptureRequest {
  authorizationId: string;
  amount: Money;
  idempotencyKey: string;
  payeeMerchantId?: string;
}

export interface CreatePayPalOrderRequest {
  localOrderId: string;
  paymentId: string;
  amount: Money;
  description: string;
  payeeMerchantId: string;
  returnUrl: string;
  cancelUrl: string;
  idempotencyKey: string;
}

export interface CreatePayPalOrderResult {
  status: "SUCCESS" | "DECLINED" | "UNKNOWN";
  orderId?: string;
  approvalUrl?: string;
  providerStatus?: string;
  errorCode?: string;
  errorMessage?: string;
}

