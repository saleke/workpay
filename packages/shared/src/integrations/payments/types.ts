/**
 * Payment gateway contract (Component 6).
 *
 * This is the only place WorkPay talks to an external payment provider. The
 * interface models three outcomes explicitly:
 *
 *   - Success   : the operation definitively succeeded.
 *   - Declined  : the provider definitively refused. A classified failure.
 *   - Unknown   : the outcome cannot be determined (timeout, network error,
 *                 ambiguous response). The caller MUST reconcile rather than
 *                 retry blindly or assume failure.
 *
 * Modelling UNKNOWN as a first-class result is what prevents double captures
 * and silent losses when the network is unreliable.
 */
import type { Money } from "../../platform/money.js";

export interface AuthorizeRequest {
  /** Merchant order id, generated by WorkPay and sent to the provider. */
  orderId: string;
  amount: Money;
  description: string;
  /** Idempotency key so a retried authorize does not create a new authorization. */
  idempotencyKey: string;
}

export interface AuthorizeResult {
  status: "SUCCESS" | "DECLINED" | "UNKNOWN";
  /** Provider authorization id, present on success. */
  authorizationId?: string;
  /** Provider order id, present on success. */
  providerOrderId?: string;
  /** Machine-readable failure code when declined. */
  errorCode?: string;
  errorMessage?: string;
}

export interface CaptureRequest {
  authorizationId: string;
  amount: Money;
  idempotencyKey: string;
}

export interface CaptureResult {
  status: "SUCCESS" | "DECLINED" | "UNKNOWN";
  captureId?: string;
  errorCode?: string;
  errorMessage?: string;
}

export interface VoidRequest {
  authorizationId: string;
  idempotencyKey: string;
}

export interface VoidResult {
  status: "SUCCESS" | "DECLINED" | "UNKNOWN";
  errorCode?: string;
  errorMessage?: string;
}

export interface RefundRequest {
  captureId: string;
  amount: Money;
  idempotencyKey: string;
}

export interface RefundResult {
  status: "SUCCESS" | "DECLINED" | "UNKNOWN";
  refundId?: string;
  errorCode?: string;
  errorMessage?: string;
}

export interface WebhookVerificationInput {
  headers: Record<string, string | undefined>;
  /** Raw request body, exactly as received, required for signature checks. */
  rawBody: string;
}

export interface WebhookVerificationResult {
  verified: boolean;
  /** Provider event id, used to dedupe redeliveries. */
  eventId?: string;
  eventType?: string;
  /** Parsed payload, present only when verified. */
  payload?: unknown;
  reason?: string;
}

export interface PaymentGateway {
  readonly name: string;
  authorize(request: AuthorizeRequest): Promise<AuthorizeResult>;
  capture(request: CaptureRequest): Promise<CaptureResult>;
  void(request: VoidRequest): Promise<VoidResult>;
  refund(request: RefundRequest): Promise<RefundResult>;
  verifyWebhook(input: WebhookVerificationInput): Promise<WebhookVerificationResult>;
}
