export interface CaptureResult {
  status: "SUCCESS" | "DECLINED" | "UNKNOWN";
  captureId?: string;
  providerStatus?: string;
  amount?: Money;
  payeeMerchantId?: string;
  orderId?: string;
  authorizationId?: string;
  errorCode?: string;
  errorMessage?: string;
}

export interface VoidRequest {
  authorizationId: string;
  idempotencyKey: string;
  payeeMerchantId?: string;
}

export interface VoidResult {
  status: "SUCCESS" | "DECLINED" | "UNKNOWN";
  errorCode?: string;
  errorMessage?: string;
}

export interface RefundRequest {
  captureId: string;
  amount: Money;
  idempotencyKey: string;
  payeeMerchantId?: string;
}

export interface RefundResult {
  status: "SUCCESS" | "DECLINED" | "UNKNOWN";
  refundId?: string;
  errorCode?: string;
  errorMessage?: string;
}

export interface WebhookVerificationInput {
  headers: Record<string, string | undefined>;
  /** Raw request body, exactly as received, required for signature checks. */
  rawBody: string;
}

export interface WebhookVerificationResult {
  status: "VERIFIED" | "INVALID" | "UNKNOWN";
  verified: boolean;
  /** Provider event id, used to dedupe redeliveries. */
  eventId?: string;
  eventType?: string;
  /** Parsed payload, present only when verified. */
  payload?: unknown;
  reason?: string;
}

export interface PaymentGateway {
  readonly name: string;
  authorize(request: AuthorizeRequest): Promise<AuthorizeResult>;
  capture(request: CaptureRequest): Promise<CaptureResult>;
  void(request: VoidRequest): Promise<VoidResult>;
  refund(request: RefundRequest): Promise<RefundResult>;
  verifyWebhook(input: WebhookVerificationInput): Promise<WebhookVerificationResult>;
}
